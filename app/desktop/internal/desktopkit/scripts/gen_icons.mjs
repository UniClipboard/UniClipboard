output+='}\n';
fs.writeFileSync(path.join(kit,'icons_gen.go'),output);
const lockPath=path.join(root,'app/desktop/boardui/reference/package-lock.json');
const lock=JSON.parse(fs.readFileSync(lockPath,'utf8'));
