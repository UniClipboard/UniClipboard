fs.mkdirSync(path.join(kit,'licenses'),{recursive:true});fs.writeFileSync(path.join(kit,'licenses/remix.txt'),license);
const source={schema:1,package:{name:packageMetadata.name,version:packageMetadata.version,license:packageMetadata.license,integrity:lock.packages['node_modules/@remixicon/react'].integrity,source:'https://registry.npmjs.org/@remixicon/react/-/react-4.9.0.tgz',entry_sha256:hash(fs.readFileSync(require.resolve('@remixicon/react'))),esm_sha256:hash(fs.readFileSync(path.join(path.dirname(packagePath),'index.mjs')))},compiler:{generator_sha256:hash(fs.readFileSync(fileURLToPath(import.meta.url))),node:process.version,react:require('react/package.json').version,lock_sha256:hash(fs.readFileSync(lockPath))},license:{path:'licenses/remix.txt',sha256:hash(license),source:'https://github.com/Remix-Design/RemixIcon/blob/v4.9.0/License'},glyphs:Object.fromEntries(Object.entries(glyphs).sort(([a],[b])=>a.localeCompare(b)).map(([name,svg])=>[name,{export:mapping[name],sha256:hash(svg)}])),cacheBound:Object.keys(glyphs).length};
fs.writeFileSync(path.join(kit,'icons-source.json'),JSON.stringify(source,null,2)+'\n');
execFileSync('gofmt',['-w',path.join(kit,'icons_gen.go')]);
console.log(JSON.stringify({package:packageMetadata.name,version:packageMetadata.version,glyphs:Object.keys(glyphs).length,manifest:path.join(kit,'icons-source.json')}));
