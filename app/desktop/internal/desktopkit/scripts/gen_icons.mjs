const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const glyphs={};
for(const[name,exportName]of Object.entries(mapping)){
 if(typeof remix[exportName]!=='function')throw Error('Missing official Remix export '+exportName);
 const svg=renderToStaticMarkup(React.createElement(remix[exportName]));
 if(!svg.includes('viewBox="0 0 24 24"')||!svg.includes('currentColor')||!svg.includes('<path'))throw Error('Unexpected official SVG '+exportName);
 glyphs[name]=svg;
}
const auditIndex=process.argv.indexOf('--audit-source');
if(process.argv.includes('--audit-before')||auditIndex>=0){
 const paths=['icons.go','icons_gen.go'].map(p=>path.join(kit,p)).filter(p=>fs.existsSync(p));
 const previous=paths.map(p=>fs.readFileSync(p,'utf8')).join('\n');
 const mismatches=Object.keys(glyphs).filter(name=>!previous.includes(JSON.stringify(glyphs[name])));
 const output=auditIndex>=0?path.resolve(process.argv[auditIndex+1]||''):path.join(root,'.build/boardui-icons/initial-red.json');
 if(fs.existsSync(output))throw Error('Refuse to overwrite source-audit evidence '+output);
 fs.mkdirSync(path.dirname(output),{recursive:true});
 fs.writeFileSync(output,JSON.stringify({scope:'source provenance audit; not rendered E2E',expectedPackage:'@remixicon/react@4.9.0',expectedGlyphCount:Object.keys(glyphs).length,missingCanonicalSVG:mismatches,pass:mismatches.length===0},null,2)+'\n');
 console.log(JSON.stringify({artifact:output,pass:mismatches.length===0,missingCanonicalSVG:mismatches.length}));
 process.exit(mismatches.length?1:0);
}
