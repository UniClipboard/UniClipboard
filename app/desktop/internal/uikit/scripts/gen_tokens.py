#!/usr/bin/env python3
"""Generate tokens_gen.go from uniclipboard's themes/default.json (raw CSS token strings per skin/scheme).
usage: gen_tokens.py default.json > tokens_gen.go"""
import json, sys
d = json.load(open(sys.argv[1]))
out = ['// Code generated by scripts/gen_tokens.py from uniclipboard themes/default.json; DO NOT EDIT.', '', 'package uikit', '',
       '// rawTokens holds the platform design tokens as CSS strings, keyed skin -> scheme -> token name (no leading "--").',
       'var rawTokens = map[string]map[string]map[string]string{']
for p in sorted(d['platforms']):
    out.append('\t%s: {' % json.dumps(p))
    for m in ('light', 'dark'):
        out.append('\t\t%s: {' % json.dumps(m))
        for k, v in sorted(d['platforms'][p][m].items()):
            out.append('\t\t\t%s: %s,' % (json.dumps(k.lstrip('-')), json.dumps(str(v))))
        out.append('\t\t},')
    out.append('\t},')
out.append('}')
print('\n'.join(out))
