// Command hosteventcodec derives the UI pipe decoder from the Wails event registrations.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
)

func main() {
	check := flag.Bool("check", false, "verify generated codecs without writing")
	flag.Parse()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "host_events.go", nil, 0)
	if err != nil {
		log.Fatal(err)
	}
	var cases bytes.Buffer
	count := 0
	ast.Inspect(file, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return true
		}
		index, ok := call.Fun.(*ast.IndexExpr)
		if !ok {
			return true
		}
		selector, ok := index.X.(*ast.SelectorExpr)
		if !ok || selector.Sel.Name != "RegisterEvent" {
			return true
		}
		pkg, ok := selector.X.(*ast.Ident)
		if !ok || pkg.Name != "application" {
			return true
		}
		if len(call.Args) != 1 {
			log.Fatal("event registration must name one event constant")
		}
		name, ok := call.Args[0].(*ast.Ident)
		if !ok {
			log.Fatal("event registration must use a constant")
		}
		var typ bytes.Buffer
		if err := format.Node(&typ, fset, index.Index); err != nil {
			log.Fatal(err)
		}
		fmt.Fprintf(&cases, "case %s: return decodeHostEventPayload[%s](data)\n", name.Name, typ.String())
		count++
		return true
	})
	if count == 0 {
		log.Fatal("no Wails event registrations found")
	}
	source := `// Code generated by go generate; DO NOT EDIT.
package main
import (
 "bytes"
 "encoding/json"
 "fmt"
 "github.com/wailsapp/wails/v3/pkg/application"
)
// decodeUIEventPayload restores the exact Wails payload type after JSON crosses the private UI pipe.
func decodeUIEventPayload(name string, data json.RawMessage) (any, error) {
 switch name {
` + cases.String() + `default: return nil, fmt.Errorf("unknown host event %q", name)
 }
}
func decodeHostEventPayload[T any](data json.RawMessage) (any, error) {
 var value T
 if err := json.Unmarshal(data, &value); err != nil { return nil, err }
 if _, void := any(value).(application.Void); void {
  if !bytes.Equal(bytes.TrimSpace(data), []byte("null")) { return nil, fmt.Errorf("void event payload must be null") }
  return nil, nil
 }
 return value, nil
}
`
	generated, err := format.Source([]byte(source))
	if err != nil {
		log.Fatal(err)
	}
	const output = "host_event_payloads_generated.go"
	if *check {
		current, err := os.ReadFile(output)
		if err != nil || !bytes.Equal(current, generated) {
			log.Fatal("host event codecs are stale: run go generate in apps/gui-go")
		}
		return
	}
	if err := os.WriteFile(output, generated, 0o644); err != nil {
		log.Fatal(err)
	}
}
